use std::collections::BTreeSet;

use num_bigint::{BigInt, BigUint};
use num_rational::BigRational;
use num_traits::{One, Signed, Zero};

use super::Multiquadratic;
use super::integer_factorization::{distinct_prime_factors, squarefree_decompose};

/// A recursively extracted twisted root.
///
/// The invariant is `source = value² * twist`, with `twist` a positive
/// squarefree integer. Tracking the twist lets a root introduce generators not
/// visible as individual radicals in the source, as in
/// `√(5 + 2√6) = √2 + √3`.
struct TwistedRoot {
    value: Multiquadratic,
    twist: BigUint,
}

impl Multiquadratic {
    /// Return the unique nonnegative square root when it is multiquadratic.
    ///
    /// A positive real multiquadratic number need not have a multiquadratic
    /// square root. This method returns `None` exactly for those values and for
    /// negative inputs.
    pub(crate) fn sqrt_exact(&self) -> Option<Self> {
        if self.signum() < 0 {
            return None;
        }

        let mut generators = BTreeSet::new();
        for (_, radicand) in self.terms() {
            generators.extend(distinct_prime_factors(&radicand));
        }
        let generators: Vec<_> = generators.into_iter().collect();
        let twisted = twisted_sqrt(self, &generators)?;
        let root = twisted.value * Multiquadratic::sqrt(twisted.twist);
        let root = if root.signum() < 0 { -root } else { root };
        (&root * &root == *self).then_some(root)
    }
}

/// Extract a root over the tower generated by `generators`.
///
/// Every recursive call removes the last prime generator. The returned twist
/// records the one-dimensional rational square class that may remain outside
/// that tower. This is the rational-coefficient form of recursive square-root
/// extraction in a multiquadratic field.
fn twisted_sqrt(source: &Multiquadratic, generators: &[BigUint]) -> Option<TwistedRoot> {
    if source.is_zero() {
        return Some(TwistedRoot {
            value: Multiquadratic::zero(),
            twist: BigUint::one(),
        });
    }
    let Some((d, lower_generators)) = generators.split_last() else {
        return twisted_sqrt_rational(source);
    };

    // source = h0 + h1√d. If source = (f0 + f1√d)² φ, its relative norm is
    // (f0² - d f1²)² φ²: an untwisted square in the smaller field.
    let (h0, h1) = source.split_on_prime(d);
    let d_value = Multiquadratic::integer(BigInt::from(d.clone()));
    let norm = &(&h0 * &h0) - &(&d_value * &(&h1 * &h1));
    let norm_root = twisted_sqrt(&norm, lower_generators)?;
    if norm_root.twist != BigUint::one() {
        return None;
    }
    let s = norm_root.value;

    // This branch handles both f1 = 0 and f0 = 0 without later dividing by 0.
    let component_square = if s == h0 {
        h0.clone()
    } else {
        (&h0 - &s) / Multiquadratic::integer(2)
    };
    let component = twisted_sqrt(&component_square, lower_generators)?;
    if component.value.is_zero() {
        return None;
    }

    let d_is_in_twist = (&component.twist % d).is_zero();
    let twist = if d_is_in_twist {
        &component.twist / d
    } else {
        component.twist.clone()
    };
    let denominator = Multiquadratic::integer(BigInt::from(2u32) * BigInt::from(twist.clone()))
        * &component.value;
    let u = &h1 / &denominator;
    let root_d = Multiquadratic::sqrt(d.clone());
    let value = if d_is_in_twist {
        u + component.value * root_d
    } else {
        component.value + u * root_d
    };

    let twist_value = Multiquadratic::integer(BigInt::from(twist.clone()));
    (&(&value * &value) * &twist_value == *source).then_some(TwistedRoot { value, twist })
}

fn twisted_sqrt_rational(source: &Multiquadratic) -> Option<TwistedRoot> {
    let (q, radicand) = source.as_single_term()?;
    if radicand != BigUint::one() || q.is_negative() {
        return None;
    }

    let numerator = q.numer().magnitude().clone();
    let denominator = q.denom().magnitude().clone();
    let (numerator_root, numerator_squarefree) = squarefree_decompose(numerator);
    let (denominator_root, denominator_squarefree) = squarefree_decompose(denominator);
    let twist = &numerator_squarefree * &denominator_squarefree;
    let rational_root = BigRational::new(
        BigInt::from(numerator_root),
        BigInt::from(denominator_root * denominator_squarefree),
    );
    let value = Multiquadratic::rational(rational_root);
    let twist_value = Multiquadratic::integer(BigInt::from(twist.clone()));
    (&(&value * &value) * &twist_value == *source).then_some(TwistedRoot { value, twist })
}

#[cfg(test)]
mod tests {
    use super::*;
    use proptest::prelude::*;

    fn q(n: i64, d: i64) -> BigRational {
        BigRational::new(BigInt::from(n), BigInt::from(d))
    }

    fn r(n: i64) -> Multiquadratic {
        Multiquadratic::integer(n)
    }

    #[test]
    fn rational_roots_are_exact() {
        assert_eq!(
            Multiquadratic::zero().sqrt_exact(),
            Some(Multiquadratic::zero())
        );
        assert_eq!(r(2).sqrt_exact(), Some(Multiquadratic::sqrt(2u32)));
        assert_eq!(
            Multiquadratic::rational(q(1, 2)).sqrt_exact(),
            Some(Multiquadratic::term(q(1, 2), 2u32))
        );
        assert_eq!(
            Multiquadratic::rational(q(4, 9)).sqrt_exact(),
            Some(Multiquadratic::rational(q(2, 3)))
        );
        assert_eq!((-r(1)).sqrt_exact(), None);
    }

    #[test]
    fn roots_inside_and_beyond_the_visible_field() {
        let s2 = Multiquadratic::sqrt(2u32);
        let s3 = Multiquadratic::sqrt(3u32);
        let s6 = Multiquadratic::sqrt(6u32);
        assert_eq!((r(3) + r(2) * &s2).sqrt_exact(), Some(r(1) + &s2));
        assert_eq!((r(3) - r(2) * &s2).sqrt_exact(), Some(&s2 - r(1)));
        assert_eq!((r(5) + r(2) * &s6).sqrt_exact(), Some(&s2 + &s3));
        assert_eq!((r(5) - r(2) * &s6).sqrt_exact(), Some(&s3 - &s2));
    }

    #[test]
    fn rejects_nonrepresentable_roots() {
        let s2 = Multiquadratic::sqrt(2u32);
        assert_eq!(s2.sqrt_exact(), None);
        assert_eq!((r(1) + &s2).sqrt_exact(), None);
        // Totally positive is necessary but not sufficient: the conjugate
        // 2 - √2 is positive, while the rational norm is the nonsquare 2.
        assert_eq!((r(2) + s2).sqrt_exact(), None);
    }

    #[test]
    fn squares_round_trip_to_the_nonnegative_root() {
        let basis = [
            r(1),
            Multiquadratic::sqrt(2u32),
            Multiquadratic::sqrt(3u32),
            Multiquadratic::sqrt(5u32),
        ];
        for a in -1..=1 {
            for b in -1..=1 {
                for c in -1..=1 {
                    for d in -1..=1 {
                        let coefficients = [a, b, c, d];
                        let value = coefficients.iter().zip(&basis).fold(
                            Multiquadratic::zero(),
                            |sum, (&coefficient, term)| {
                                sum + Multiquadratic::integer(coefficient) * term
                            },
                        );
                        let square = &value * &value;
                        let expected = if value.signum() < 0 { -&value } else { value };
                        assert_eq!(square.sqrt_exact(), Some(expected));
                    }
                }
            }
        }
    }

    #[test]
    fn dense_fractional_square_avoids_large_integer_factorization() {
        let value = Multiquadratic::rational(q(3, 5))
            - Multiquadratic::rational(q(2, 3)) * Multiquadratic::sqrt(2u32)
            + Multiquadratic::rational(q(4, 7)) * Multiquadratic::sqrt(3u32)
            - Multiquadratic::rational(q(1, 2)) * Multiquadratic::sqrt(5u32);
        let square = &value * &value;
        let expected = if value.signum() < 0 { -value } else { value };
        assert_eq!(square.sqrt_exact(), Some(expected));
    }

    #[test]
    fn huge_rational_square_does_not_need_factorization() {
        let numerator = (BigInt::one() << 521) - BigInt::one();
        let denominator = (BigInt::one() << 127) + BigInt::one();
        let value = Multiquadratic::rational(BigRational::new(numerator, denominator));
        assert_eq!((&value * &value).sqrt_exact(), Some(value));
    }

    proptest! {
        #![proptest_config(ProptestConfig::with_cases(64))]

        #[test]
        fn rational_multiquadratic_squares_round_trip(
            a in -20i32..=20,
            b in -20i32..=20,
            c in -20i32..=20,
            denominator in 1i32..=12,
        ) {
            let value = Multiquadratic::rational(BigRational::new(a.into(), denominator.into()))
                + Multiquadratic::rational(BigRational::new(b.into(), denominator.into()))
                    * Multiquadratic::sqrt(2u32)
                + Multiquadratic::rational(BigRational::new(c.into(), denominator.into()))
                    * Multiquadratic::sqrt(3u32);
            let square = &value * &value;
            let expected = if value.signum() < 0 { -value } else { value };
            prop_assert_eq!(square.sqrt_exact(), Some(expected));
        }
    }
}
